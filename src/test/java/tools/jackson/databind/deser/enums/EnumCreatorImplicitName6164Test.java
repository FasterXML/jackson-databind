package tools.jackson.databind.deser.enums;

import org.junit.jupiter.api.Test;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonProperty;

import tools.jackson.databind.ObjectMapper;
import tools.jackson.databind.testutil.DatabindTestUtil;

import static org.junit.jupiter.api.Assertions.assertEquals;

// [databind#6164]: single-arg `@JsonCreator` on Enum whose implicit parameter
// name matches a getter should not be detected as properties-based
public class EnumCreatorImplicitName6164Test extends DatabindTestUtil
{
    enum DataSetType6164 {
        ZERO(0), FIVE(5);

        private final int value;

        DataSetType6164(int value) { this.value = value; }

        // as generated by Lombok `@Getter`; matches creator parameter name
        public int getValue() { return value; }

        @JsonCreator
        public static DataSetType6164 getDataSetTypeByValue(int value) {
            for (DataSetType6164 t : values()) {
                if (t.value == value) {
                    return t;
                }
            }
            return null;
        }
    }

    static class Wrapper6164 {
        public DataSetType6164 dataSetType;
    }

    // Explicit parameter name still indicates properties-based
    enum ExplicitlyNamed6164 {
        ZERO(0), FIVE(5);

        private final int value;

        ExplicitlyNamed6164(int value) { this.value = value; }

        public int getValue() { return value; }

        @JsonCreator
        public static ExplicitlyNamed6164 of(@JsonProperty("value") int value) {
            for (ExplicitlyNamed6164 t : values()) {
                if (t.value == value) {
                    return t;
                }
            }
            return null;
        }
    }

    // Enums serialized as JSON Objects retain the implicit-name heuristic
    @JsonFormat(shape = JsonFormat.Shape.OBJECT)
    enum AsObject6164 {
        ZERO(0), FIVE(5);

        private final int value;

        AsObject6164(int value) { this.value = value; }

        public int getValue() { return value; }

        @JsonCreator
        public static AsObject6164 of(int value) {
            for (AsObject6164 t : values()) {
                if (t.value == value) {
                    return t;
                }
            }
            return null;
        }
    }

    private final ObjectMapper MAPPER = newJsonMapper();

    @Test
    void implicitNameMatchingGetterIsDelegating() throws Exception
    {
        assertEquals(DataSetType6164.FIVE, MAPPER.readValue("5", DataSetType6164.class));
        assertEquals(DataSetType6164.ZERO, MAPPER.readValue("0", DataSetType6164.class));
    }

    @Test
    void implicitNameMatchingGetterAsProperty() throws Exception
    {
        Wrapper6164 w = MAPPER.readValue("""
                {"dataSetType":5}
                """, Wrapper6164.class);
        assertEquals(DataSetType6164.FIVE, w.dataSetType);
    }

    @Test
    void explicitNameIsPropertiesBased() throws Exception
    {
        assertEquals(ExplicitlyNamed6164.FIVE, MAPPER.readValue("""
                {"value":5}
                """, ExplicitlyNamed6164.class));
    }

    @Test
    void objectShapeIsPropertiesBased() throws Exception
    {
        assertEquals(AsObject6164.FIVE, MAPPER.readValue("""
                {"value":5}
                """, AsObject6164.class));
        // and round-trip
        assertEquals(AsObject6164.FIVE, MAPPER.readValue(
                MAPPER.writeValueAsString(AsObject6164.FIVE), AsObject6164.class));
    }
}
